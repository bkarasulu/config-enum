"""Generate docs/cli.md from the argument parser (run: python docs/gen_cli.py)."""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "src"))
os.environ.pop("VASP_PP_PATH", None)  # the choices of --potcarxc depend on it

from config_enum.cli import build_parser  # noqa: E402

# first option (dest) of each section, in the order of the parser
SECTIONS = {"inpf": "Input and output", "ifPrim": "Structure and symmetry", "list": "Sites and dopants",
            "modify": "Modifications, interstices and final checks", "castep": "Energies: VASP and CASTEP",
            "nprocs": "Parallelisation", "temp": "Thermodynamics and sequential doping", "verb": "General",
            "ase_pot": "ASE calculators (simple and machine-learning potentials)", "mlip": "Machine-learning potentials",
            "input": "Input files"}


def _default(a):
    if isinstance(a, (argparse._StoreTrueAction, argparse._StoreFalseAction)) or a.default in (None, False, ""):
        return ""
    d = a.default
    if isinstance(d, (list, tuple)):
        d = " ".join(str(v) for v in d)
    return "`%s`" % d


def generate():
    parser = build_parser()
    lines = ["# Command-line reference", "",
             "<!-- generated by docs/gen_cli.py from config_enum.cli.build_parser; do not edit by hand -->", "",
             "`config_enum [options]` and `python config_enum.py [options]` take the same options.",
             "Every option except `--input`, `--save_input`, `--help` and `--version` can also go in an input file "
             "(see [Input files](input_files.md)); the file key is the long name without dashes (e.g. `noDopants`) or the short name (e.g. `nd`).", ""]
    for a in parser._actions:
        if a.dest in SECTIONS:
            lines += ["", "## " + SECTIONS[a.dest], "", "| Option | Default | Description |", "|---|---|---|"]
        if a.dest == "help":
            continue
        opts = ", ".join("`%s`" % o for o in a.option_strings)
        if a.choices and a.dest != "potcarxc":
            opts += " {%s}" % ",".join(map(str, a.choices))
        help_ = (a.help or "").replace("|", "\\|").replace("\n", " ")
        lines.append("| %s | %s | %s |" % (opts, _default(a), help_))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    with open(os.path.join(HERE, "cli.md"), "w") as f:
        f.write(generate())
    print("wrote docs/cli.md")
